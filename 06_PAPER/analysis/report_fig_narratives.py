def get_narrative(fname: str) -> dict[str, str] | None:
    base = NARRATIVES.get(fname)
    if base is None:
        return None
    # EXTRA_DEEP 覆盖薄弱字段；数字仍锚定 analysis JSON / 既有图面。
    try:
        from report_fig_narratives_extra import EXTRA_DEEP
    except ImportError:  # pragma: no cover
        EXTRA_DEEP = {}
    try:
        from report_fig_narratives_autodepth import AUTO_DEEP
    except ImportError:  # pragma: no cover
        AUTO_DEEP = {}
    merged = {
        **base,
        **DEEP_LAYERS.get(fname, {}),
        **EXTRA_DEEP.get(fname, {}),
        **AUTO_DEEP.get(fname, {}),
    }
    return merged
